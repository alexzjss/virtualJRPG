// as variações entram na linha da técnica (ramo com `de`), criando a linha se ainda não existir
export function variar8(TREE) {
  const all = () => Object.values(TREE).flatMap(t => t.branches);
  for (const [base, vs] of Object.entries(VAR8)) {
    const ab = TREE.armas.branches.find(b => b.some(s => s.n === base)); // a Árvore de Armas não tem linhas: as variações entram no ramo, logo depois da base
    if (ab) { ab.splice(ab.findIndex(s => s.n === base) + 1, 0, ...vs); continue; }
    let L = all().find(b => b.de === base);
    if (!L) { const t = Object.values(TREE).find(t => t.branches.some(b => b.some(s => s.n === base))); if (!t) throw new Error(`Leva 8: base "${base}" não existe`); L = []; L.de = base; t.branches.push(L); }
    L.push(...vs);
  }
}
